/** Ordenado alfabeticamente en el idioma pedido. */
export function countriesFor(locale: 'en' | 'ru' | 'es'): {
  code: string
  dial: string
  label: string
}[] {
  return COUNTRIES.map((c) => ({
    code: c.code,
    dial: c.dial,
    label: c.name[locale] ?? c.name.en ?? c.code,
  })).sort((a, b) => a.label.localeCompare(b.label, locale))
}
